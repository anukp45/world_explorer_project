# Fast lookup table for every question by ID:
# question_id -> question_dict
_QUESTION_INDEX: Dict[str, Dict[str, Any]] = {}

def _init_question_index() -> None:
    _QUESTION_INDEX.clear()
    for challenge_id, diff_dict in CURATED_QUESTIONS.items():
        for diff_level, q_list in diff_dict.items():
            for q in q_list:
                _QUESTION_INDEX[q["id"]] = q

_init_question_index()


def get_question_by_id(challenge_id: str, question_id: str) -> Optional[Dict[str, Any]]:
    """Lookup a question by its unique ID across all question pools."""
    return _QUESTION_INDEX.get(question_id)


def get_daily_challenge(
    challenge_id: str,
    date_str: Optional[str] = None,
    difficulty: str = "mixed",
) -> Optional[Dict[str, Any]]:
    """Generate the deterministic 10-question daily challenge for a given challenge ID and day.

    difficulty can be:
      - 'mixed' (default): 3 Easy, 4 Medium, 3 Hard questions (total 10)
      - 'easy': 10 Easy questions
      - 'medium': 10 Medium questions
      - 'hard': 10 Hard questions
    """
    if challenge_id not in CHALLENGE_METADATA:
        return None

    meta = CHALLENGE_METADATA[challenge_id]
    pools = CURATED_QUESTIONS.get(challenge_id, {})
    if not pools:
        return None

    if date_str is None:
        date_str = date.today().isoformat()

    difficulty = (difficulty or "mixed").lower()
    if difficulty not in ("mixed", "easy", "medium", "hard"):
        difficulty = "mixed"

    # Deterministic pseudo-random generator seeded by date + challenge + difficulty
    seed_key = f"{date_str}:{challenge_id}:{difficulty}"
    seed_num = int(hashlib.sha256(seed_key.encode("utf-8")).hexdigest()[:14], 16)
    rng = random.Random(seed_num)

    selected_questions: List[Dict[str, Any]] = []

    if difficulty == "mixed":
        easy_pool = list(pools.get("easy", []))
        med_pool = list(pools.get("medium", []))
        hard_pool = list(pools.get("hard", []))

        rng.shuffle(easy_pool)
        rng.shuffle(med_pool)
        rng.shuffle(hard_pool)

        # 3 Easy, 4 Medium, 3 Hard = 10 total
        selected_questions.extend(easy_pool[:3])
        selected_questions.extend(med_pool[:4])
        selected_questions.extend(hard_pool[:3])
    else:
        pool = list(pools.get(difficulty, []))
        rng.shuffle(pool)
        selected_questions = pool[:10]

    # Ensure exactly 10 questions (fallback if a pool was slightly short)
    if len(selected_questions) < 10:
        all_remaining = [
            q for diff_list in pools.values() for q in diff_list
            if q not in selected_questions
        ]
        rng.shuffle(all_remaining)
        selected_questions.extend(all_remaining[: 10 - len(selected_questions)])

    return {
        "id": meta["id"],
        "title": meta["title"],
        "category": meta["category"],
        "description": meta["description"],
        "difficulty": difficulty,
        "date": date_str,
        "questions_count": len(selected_questions),
        "questions": selected_questions,
    }


def get_daily_challenges(
    date_str: Optional[str] = None,
    difficulty: str = "mixed",
) -> List[Dict[str, Any]]:
    """Return all 5 daily challenges with 10 questions each for the specified date."""
    if date_str is None:
        date_str = date.today().isoformat()

    challenges = []
    for cid in CHALLENGE_METADATA:
        ch = get_daily_challenge(cid, date_str=date_str, difficulty=difficulty)
        if ch:
            challenges.append(ch)
    return challenges


def public_challenge_dto(challenge: Dict[str, Any]) -> Dict[str, Any]:
    """Convert an internal challenge dict to a safe public JSON structure without correct answers."""
    return {
        "id": challenge["id"],
        "title": challenge["title"],
        "category": challenge["category"],
        "description": challenge["description"],
        "difficulty": challenge.get("difficulty", "mixed"),
        "date": challenge.get("date"),
        "questions_count": len(challenge["questions"]),
        "questions": [
            {
                "id": q["id"],
                "question": q["question"],
                "choices": q["choices"],
                "difficulty": q.get("difficulty", "medium"),
            }
            for q in challenge["questions"]
        ],
    }
